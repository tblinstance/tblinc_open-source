def run_model(model_key: str, custom_input: Any = None) -> dict[str, Any]:
    """Execute inference using the latest trained checkpoint from Admin TrainingRun when available."""
    try:
        from tblinc.web.admin.trainer import load_or_fit_live_model

        t0 = time.perf_counter()
        live_model, ckpt_source = load_or_fit_live_model(model_key)
        inp = custom_input if custom_input is not None else live_model.metadata.input_example
        pred = live_model.predict(inp)
        elapsed_ms = round((time.perf_counter() - t0) * 1000.0, 2)
        return {
            "training": live_model.training_metrics,
            "checkpoint": ckpt_source,
            "elapsed_ms": elapsed_ms,
            "model": live_model.metadata.to_dict(),
            "result": pred.to_dict(),
        }
    except Exception:
        return run_demo(model_key, custom_input=custom_input)
