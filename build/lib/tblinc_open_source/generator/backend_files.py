class AIPredictController(Controller):
    """Admin or API-Key authenticated MVC Controller executing any built-in AI model with live token quota metering."""

    def post(self, request: Request, model_key: str) -> Response:
        from tblinc.web.admin.quota import (
            authenticate_api_key,
            check_quota,
            estimate_tokens,
            record_token_usage,
        )

        api_key_obj = authenticate_api_key(request, model_key=model_key)
        is_staff = request.user is not None and (request.user.is_staff or request.user.is_superuser)
        if api_key_obj is None and not is_staff:
            raise Http403("Admin login (/admin/login/) or valid X-API-Key / Bearer token required.")

        payload = request.json() if request.body else {}
        custom_input = payload.get("input") if isinstance(payload, dict) else None
        username = (
            request.user.username
            if request.user is not None
            else ((api_key_obj.owner_username or api_key_obj.name) if api_key_obj else "api")
        )
        p_tokens = estimate_tokens(custom_input, modality=model_key)
        check_quota(model_key, prompt_tokens=p_tokens, api_key_obj=api_key_obj, username=username)

        try:
            output = run_model(model_key, custom_input=custom_input)
        except KeyError as exc:
            raise Http404(str(exc)) from exc

        res = output.get("result", {})
        c_tokens = estimate_tokens(res, modality=model_key)
        latency = float(res.get("latency_ms") or output.get("elapsed_ms") or 0.0)
        usage = record_token_usage(
            model_key,
            prompt_tokens=p_tokens,
            completion_tokens=c_tokens,
            latency_ms=latency,
            api_key_obj=api_key_obj,
            username=username,
        )
        output["usage"] = usage

        InferenceLog.objects.create(
            model_key=model_key,
            input_payload=custom_input if isinstance(custom_input, dict) else {"value": custom_input},
            output_prediction=str(res.get("prediction", ""))[:500],
            confidence=float(res.get("confidence") or 0.0),
            latency_ms=latency,
        )
        return self.json(output)
